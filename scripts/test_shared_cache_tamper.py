class PreMintRetargetTests(unittest.TestCase):
    """A VM booted with the shared cache is never retargeted to a release tier."""

    def retarget(self, to_label: str, shared: str) -> tuple[int, str, str]:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        calls = Path(tmp.name) / "calls"
        calls.touch()
        body = function_body(RUNNER.read_text(encoding="utf-8"), "retarget_after_pre_mint_denial")
        script = (RETARGET_STUBS + 'source "$1"; shift\n' + body
                  + '\nrc=0; retarget_after_pre_mint_denial 1 1 || rc=$?\n'
                  'echo "rc=$rc labels=$selected_labels"\n')
        result = subprocess.run(["/bin/bash", "-c", script, "_", str(calls), str(LIB)],
                                text=True, capture_output=True, check=False,
                                env={"PATH": "/usr/bin:/bin", "TO_LABEL": to_label,
                                     "CURRENT_SHARED_CACHE": shared})
        return result.returncode, result.stdout + result.stderr, calls.read_text()

    def test_a_shared_cache_vm_is_discarded_rather_than_retargeted_to_release(self) -> None:
        _, out, calls = self.retarget("pulp-release-tagged", "1")
        self.assertIn("rc=1 ", out)
        self.assertIn("discard", calls)
        self.assertIn("reason=release_tier_no_shared_cache", calls)

    def test_other_retargets_still_happen(self) -> None:
        # Control: the same VM retargets to a gate class.
        _, out, calls = self.retarget("pulp-release-pr-gate", "1")
        self.assertIn("rc=0 labels=self-hosted,macOS,ARM64,pulp-build-vm,pulp-release-pr-gate", out)
        self.assertNotIn("discard", calls)
        # Control: a VM booted without the shared cache may serve the release tier.
        _, out, calls = self.retarget("pulp-release-tagged", "0")
        self.assertIn("rc=0 labels=", out)
        self.assertNotIn("discard", calls)


