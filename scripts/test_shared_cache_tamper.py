class BootArgvTests(unittest.TestCase):
    def setUp(self) -> None:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.base = Path(os.path.realpath(tmp.name))
        self.root = self.base / "pulp-ci"
        self.calls = self.base / "calls"

    def boot(self, labels: str, **env: str) -> tuple[int, list[str], str]:
        body = function_body(RUNNER.read_text(encoding="utf-8"), "boot_vm_to_ssh")
        script = (BOOT_STUBS + 'source "$1"; shift\n'
                  'CACHE_ROOT="$1" HOST_CACHE_ROOT="" FETCHCONTENT_SOURCE_ROOT="$2"\n'
                  + body + '\nboot_vm_to_ssh 1 vm-1 "$3" gate log; rc=$?; wait\n'
                  'echo "rc=$rc shared=$CURRENT_SHARED_CACHE"\n')
        result = subprocess.run(
            ["/bin/bash", "-c", script, "_", str(self.calls), str(LIB), str(self.root),
             str(self.base / "fetchcontent"), labels],
            text=True, capture_output=True, check=False,
            env={"PATH": "/usr/bin:/bin", "TMPDIR": str(self.base), **env})
        argv_file = Path(str(self.calls) + ".argv")
        argv = argv_file.read_text().splitlines() if argv_file.exists() else []
        return result.returncode, argv, result.stdout + result.stderr

    def dirs(self, argv: list[str]) -> list[str]:
        return [a.split("=", 1)[1].split(":", 1)[0] for a in argv if a.startswith("--dir=")]

    def test_a_pr_head_boot_mounts_both_read_write_caches(self) -> None:
        rc, argv, out = self.boot("self-hosted,macOS,ARM64,pulp-build-vm,pulp-build-pr-head")
        self.assertEqual(rc, 0, out)
        self.assertIn("rc=0 shared=1", out)
        self.assertEqual(argv[:2], ["tart", "run"])
        self.assertEqual(self.dirs(argv), ["ccache", "fetchcontent", "configure-checks"])
        self.assertIn(f"--dir=ccache:{self.root}/ccache", argv)
        self.assertIn(f"--dir=configure-checks:{self.root}/configure-checks", argv)

    def test_a_release_tagged_boot_mounts_neither(self) -> None:
        rc, argv, out = self.boot("self-hosted,macOS,ARM64,pulp-build-vm,pulp-release-tagged")
        self.assertEqual(rc, 0, out)
        self.assertIn("rc=0 shared=0", out)
        self.assertEqual(self.dirs(argv), ["fetchcontent"])
        self.assertIn("event shared_cache_skipped", self.calls.read_text())

    def test_the_knob_off_restores_the_release_mounts(self) -> None:
        rc, argv, out = self.boot("self-hosted,pulp-build-vm,pulp-release-tagged",
                                  TARTCI_RELEASE_TIER_NO_SHARED_CACHE="0")
        self.assertEqual(rc, 0, out)
        self.assertEqual(self.dirs(argv), ["ccache", "fetchcontent", "configure-checks"])

    def test_a_planted_ccache_conf_stops_a_gate_boot_but_not_a_release_boot(self) -> None:
        (self.root / "ccache").mkdir(parents=True)
        conf = self.root / "ccache" / "ccache.conf"
        conf.write_text("prefix_command = /usr/bin/true\n")
        rc, argv, out = self.boot("self-hosted,pulp-build-vm,pulp-build-pr-head")
        self.assertIn("rc=1 shared=1", out)
        self.assertEqual(argv, [], "no VM may boot on a tampered cache")
        calls = self.calls.read_text()
        self.assertIn(f"note [1] shared cache: {conf} is a ccache config with a setting", calls)
        self.assertIn("refusing to boot", calls)
        self.assertIn("complete fail cache_setup_failed", calls)
        # The release boot mounts neither directory, so the plant cannot reach it.
        self.calls.unlink()
        rc, argv, out = self.boot("self-hosted,pulp-build-vm,pulp-release-tagged")
        self.assertIn("rc=0 shared=0", out)
        self.assertEqual(self.dirs(argv), ["fetchcontent"])


