#!/usr/bin/env python3
"""What a guest leaves in the shared caches cannot run as code anywhere else.

Every Tart guest mounts $CACHE_ROOT/ccache and $CACHE_ROOT/configure-checks
read-write. Two files there are code for whoever reads them next: a
ccache.conf (prefix_command runs on the next compile) and a configure-checks
*.cmake file, which Pulp's PulpConfigureCheckCache.cmake include()s. These
tests cover, each beside its control:

  * the pre-boot refusal (and the opt-in quarantine) in lane-cache-root.lib.sh;
  * the guest command: ccache reads a guest-local CCACHE_CONFIGPATH;
  * release-tier boots mount neither read-write cache (the tart argv).
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import ccache_guard  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
RUNNER = ROOT / "providers" / "tart-macos" / "runner.sh"
LIB = ROOT / "providers" / "tart-macos" / "lane-cache-root.lib.sh"

HEADER = "# Generated by PulpConfigureCheckCache.cmake. Safe to delete.\n"
# Lines in the exact form Pulp's writer produces (taken from a real SDL3 file).
GOOD_SEED = HEADER + "".join(
    f"pulp_configure_check_cache_seed({line})\n" for line in (
        'COMPILER_HAS_SEM_TIMEDWAIT "" "Test COMPILER_HAS_SEM_TIMEDWAIT"',
        'HAVE_ALLOCA_H "1" "Have include alloca.h"',
        'HAVE_DLOPEN_IN_LIBC "1" "Have symbol dlopen"',
        'HAVE_X "0" "Have include sys/a.h\\;b.h"',
        'HAVE_Y "1" "Have symbol a\\$b \\"q\\" \\\\"',
        'HAVE_Z "TRUE" "Result of TRY_COMPILE"',
    ))


def function_body(source: str, name: str) -> str:
    match = re.search(rf"^{name}\(\)\{{\n(.*?)^\}}$", source, re.MULTILINE | re.DOTALL)
    if match is None:
        raise AssertionError(f"missing function {name}")
    return match.group(0)


def lib(snippet: str, *args: str, env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["/bin/bash", "-c", 'source "$1"; shift; ' + snippet, "_", str(LIB), *args],
        text=True, capture_output=True, check=False,
        env={"PATH": "/usr/bin:/bin", **(env or {})},
    )


class TamperRefusalTests(unittest.TestCase):
    def setUp(self) -> None:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(os.path.realpath(tmp.name)) / "pulp-ci"
        (self.root / "ccache").mkdir(parents=True)
        (self.root / "configure-checks").mkdir()
        self.seed = self.root / "configure-checks" / "SDL3-133c8fb58063bd73bc89cc6e.cmake"
        self.seed.write_text(GOOD_SEED)

    def refusal(self, mode: str | None = None) -> subprocess.CompletedProcess[str]:
        env = {} if mode is None else {"TARTCI_CACHE_TAMPER": mode}
        return lib('tartci_shared_cache_tamper_refusal "$1"', str(self.root), env=env)

    def test_a_clean_root_with_writer_format_seeds_boots(self) -> None:
        result = self.refusal()
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(result.stdout, "")

    def test_an_empty_root_boots(self) -> None:
        self.seed.unlink()
        self.assertEqual(self.refusal().returncode, 0)

    def test_a_planted_ccache_conf_is_refused_with_its_path(self) -> None:
        conf = self.root / "ccache" / "ccache.conf"
        conf.write_text("prefix_command = /bin/sh -c 'touch /tmp/pwned'\n")
        result = self.refusal()
        self.assertEqual(result.returncode, 1)
        self.assertIn(f"{conf} is a ccache config with a setting beyond size and hashing",
                      result.stdout)
        self.assertIn("TARTCI_CACHE_TAMPER=quarantine", result.stdout)
        self.assertTrue(conf.exists(), "refuse mode must not touch the file")
        # Control: removed, the same root boots.
        conf.unlink()
        self.assertEqual(self.refusal().returncode, 0)

    def test_ccache_conf_settings_that_name_a_command_or_path_are_refused(self) -> None:
        conf = self.root / "ccache" / "ccache.conf"
        for text in ("prefix_command = /bin/sh -c id\n",
                     "prefix_command_cpp = /bin/sh\n",
                     "compiler_check = %compiler% -v\n",
                     "compiler_check = /bin/sh -c id\n",
                     "cache_dir = /tmp/elsewhere\n",
                     "remote_storage = file:/tmp/x\n",
                     "log_file = /etc/x\n",
                     "max_size = 40G; prefix_command = /bin/sh\n",
                     "max_size = 40G\nrun_second_cpp = false\n"):
            with self.subTest(text=text):
                conf.write_text(text)
                self.assertEqual(self.refusal().returncode, 1, text)

    def test_a_size_and_hashing_ccache_conf_boots(self) -> None:
        # What Pulp's pulp-worktree.sh and ccache --set-config write there.
        conf = self.root / "ccache" / "ccache.conf"
        for text in ("max_size = 40G\n",
                     "# Set by ccache\nmax_size = 5.0 GB\n\ncompression = true\n",
                     "inode_cache = true\nhash_dir = false\ncompiler_check = content\n"
                     "depend_mode = false\nmax_files = 0\ncompression_level = -1\n"):
            with self.subTest(text=text):
                conf.write_text(text)
                result = self.refusal()
                self.assertEqual(result.returncode, 0, result.stdout)

    def test_a_ccache_conf_directory_is_refused(self) -> None:
        (self.root / "ccache" / "ccache.conf").mkdir()
        result = self.refusal()
        self.assertEqual(result.returncode, 1)
        self.assertIn("is not a regular file", result.stdout)

    def test_a_dangling_ccache_conf_link_is_refused(self) -> None:
        (self.root / "ccache" / "ccache.conf").symlink_to(self.root / "nowhere")
        self.assertEqual(self.refusal().returncode, 1)

    def test_a_malicious_seed_is_refused(self) -> None:
        bad = {
            "execute_process": "execute_process(COMMAND touch /tmp/pwned)\n",
            "trailing command": 'pulp_configure_check_cache_seed(X "1" "Test X") '
                                "execute_process(COMMAND id)\n",
            "unescaped variable": 'pulp_configure_check_cache_seed(X "1" "Have symbol ${ENV{HOME}}")\n',
            "escaped backslash closes the quote": 'pulp_configure_check_cache_seed(X "1" '
                                                  '"Have symbol a\\\\" ) execute_process(COMMAND id) #")\n',
            "non-boolean value": 'pulp_configure_check_cache_seed(X "/bin/sh" "Test X")\n',
            "variable in the name": 'pulp_configure_check_cache_seed(${X} "1" "Test X")\n',
            "other comment": "#[[ bracket comment ]]\n",
            "carriage return": 'pulp_configure_check_cache_seed(X "1" "Test X")\r\n',
            "CMAKE_ variable": 'pulp_configure_check_cache_seed(CMAKE_POSITION_INDEPENDENT_CODE '
                               '"OFF" "Test CMAKE_POSITION_INDEPENDENT_CODE")\n',
        }
        for name, line in bad.items():
            with self.subTest(name=name):
                planted = self.root / "configure-checks" / "SDL3-0123456789abcdef01234567.cmake"
                planted.write_text(HEADER + line)
                result = self.refusal()
                self.assertEqual(result.returncode, 1, line)
                self.assertIn(f"{planted} holds a line that is not a configure-check seed",
                              result.stdout)
                planted.unlink()
        # Control: the writer-format file beside them is accepted.
        self.assertEqual(self.refusal().returncode, 0)

    def test_a_seed_with_an_upper_case_extension_is_refused(self) -> None:
        # The cache volume is case-insensitive APFS: Pulp's include() of
        # <name>-<key>.cmake opens SDL3-<key>.CMAKE as well.
        for name in ("SDL3-cccccccccccccccccccccccc.CMAKE", "SDL3-dddddddddddddddddddddddd.Cmake"):
            with self.subTest(name=name):
                planted = self.root / "configure-checks" / name
                planted.write_text(HEADER + "execute_process(COMMAND touch /tmp/pwned)\n")
                result = self.refusal()
                self.assertEqual(result.returncode, 1, result.stdout)
                self.assertIn(f"{planted} holds a line that is not a configure-check seed",
                              result.stdout)
                quarantined = self.refusal("quarantine")
                self.assertEqual(quarantined.returncode, 0, quarantined.stdout + quarantined.stderr)
                self.assertFalse(planted.exists())
                self.assertTrue(self.seed.exists(), "a clean seed must stay in place")
        # Control: a writer-format seed under an upper-case name still boots.
        (self.root / "configure-checks" / "SDL3-eeeeeeeeeeeeeeeeeeeeeeee.CMAKE").write_text(GOOD_SEED)
        self.assertEqual(self.refusal().returncode, 0)

    def test_a_symlinked_seed_is_refused(self) -> None:
        # Read in the guest, a link resolves to whatever that guest (or the
        # other shared mount) holds.
        target = self.root / "ccache" / "payload"
        target.write_text("execute_process(COMMAND id)\n")
        link = self.root / "configure-checks" / "SDL3-aaaaaaaaaaaaaaaaaaaaaaaa.cmake"
        link.symlink_to(target)
        result = self.refusal()
        self.assertEqual(result.returncode, 1)
        self.assertIn(f"{link} is not a regular file", result.stdout)

    def test_an_unreadable_seed_fails_closed(self) -> None:
        if os.geteuid() == 0:
            self.skipTest("root reads any file")
        self.seed.chmod(0)
        self.addCleanup(self.seed.chmod, 0o644)
        self.assertEqual(self.refusal().returncode, 1)

    def test_quarantine_moves_only_the_bad_files_and_boots(self) -> None:
        conf = self.root / "ccache" / "ccache.conf"
        conf.write_text("prefix_command = /usr/bin/true\n")
        planted = self.root / "configure-checks" / "SDL3-bbbbbbbbbbbbbbbbbbbbbbbb.cmake"
        planted.write_text("execute_process(COMMAND id)\n")
        result = self.refusal("quarantine")
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertFalse(conf.exists())
        self.assertFalse(planted.exists())
        self.assertTrue(self.seed.exists(), "a clean seed must stay in place")
        moved_conf = list((self.root / "ccache-quarantine").glob("*-tamper/ccache.conf"))
        moved_seed = list((self.root / "configure-checks-quarantine").glob(f"*-tamper/{planted.name}"))
        self.assertEqual(len(moved_conf), 1)
        self.assertEqual(len(moved_seed), 1)
        self.assertIn("quarantined", result.stderr)
        self.assertEqual(self.refusal().returncode, 0)

    def test_an_unknown_mode_refuses(self) -> None:
        (self.root / "ccache" / "ccache.conf").write_text("prefix_command = /usr/bin/true\n")
        result = self.refusal("ignore")
        self.assertEqual(result.returncode, 1)
        self.assertIn("is not refuse or quarantine", result.stdout)
        self.assertTrue((self.root / "ccache" / "ccache.conf").exists())

    def test_the_mount_preparation_refuses_only_when_it_mounts_the_shared_cache(self) -> None:
        (self.root / "ccache" / "ccache.conf").write_text("prefix_command = /usr/bin/true\n")
        stubs = ('tartci_prepare_disk_root(){ mkdir -p "$1"; }\n'
                 'tartci_ccache_guard(){ :; }\n')
        script = (stubs + 'tartci_prepare_lane_cache_mounts "$1" "" "$2" "$3"; rc=$?\n'
                  'printf "rc=%s refusal=%s\\n" "$rc" "$TARTCI_LANE_CACHE_REFUSAL"')
        fetch = str(self.root.parent / "fetchcontent")
        mounted = lib(script, str(self.root), fetch, "1")
        self.assertIn("rc=1 refusal=shared cache: ", mounted.stdout)
        # Default (no fourth argument) is the mounting boot.
        default = lib(stubs + 'tartci_prepare_lane_cache_mounts "$1" "" "$2"; echo "rc=$?"',
                      str(self.root), fetch)
        self.assertIn("rc=1", default.stdout)
        unmounted = lib(script, str(self.root), fetch, "0")
        self.assertIn("rc=0 refusal=\n", unmounted.stdout)


