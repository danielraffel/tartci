# shellcheck shell=bash
# A lane-owned cache root (fleet profile `cache_root`) must be the directory
# its path names. The profile validator compares paths as text; a symlink in
# the root, or in its ccache or configure-checks subdirectory, would make the
# VM mount whatever the link points at, the host-wide root that every PR gate
# VM writes included. TARTCI_HOST_CI_CACHE is set only for such a lane.

tartci_physical_dir() {
  (cd "$1" 2>/dev/null && pwd -P)
}

# Prints the reason and returns 1 when the lane root is unsafe to mount.
tartci_lane_cache_root_refusal() {
  local root="$1" host="${2:-}" dir physical root_physical host_physical
  [ -n "$host" ] || return 0
  for dir in "$root" "$root/ccache" "$root/configure-checks"; do
    # Not created yet is fine: the disk-root preparation creates it without
    # following links. A link, or an existing path that resolves elsewhere,
    # is not.
    if [ -L "$dir" ]; then
      printf 'lane cache root: %s is a symlink; it would mount another cache\n' "$dir"
      return 1
    fi
    [ -e "$dir" ] || continue
    if ! physical="$(tartci_physical_dir "$dir")"; then
      printf 'lane cache root: %s is not a directory\n' "$dir"
      return 1
    fi
    if [ "$physical" != "$dir" ]; then
      printf 'lane cache root: %s resolves to %s; a symlink would mount another cache\n' \
        "$dir" "$physical"
      return 1
    fi
  done
  root_physical="$(tartci_physical_dir "$root" || printf '%s' "$root")"
  host_physical="$(tartci_physical_dir "$host" || printf '%s' "$host")"
  case "$root_physical/" in
    "$host_physical/"*)
      printf 'lane cache root: %s is or sits inside the host cache root %s\n' \
        "$root_physical" "$host_physical"
      return 1 ;;
  esac
  case "$host_physical/" in
    "$root_physical/"*)
      printf 'lane cache root: %s contains the host cache root %s\n' \
        "$root_physical" "$host_physical"
      return 1 ;;
  esac
  return 0
}

# Checks and prepares every directory a VM mounts from the cache root, in the
# order the boot needs: refuse an unsafe lane root before anything is created
# or trimmed through it, prepare ccache (then quarantine bad manifests), the
# FetchContent source root and configure-checks, then refuse again now that
# every mounted directory exists, and (when the boot mounts the shared cache,
# argument 4 = 1, the default) refuse a tampered one. On a refusal TARTCI_LANE_CACHE_REFUSAL holds
# the reason; a failed preparation leaves it empty. Returns 1 either way.
# shellcheck disable=SC2034 # TARTCI_LANE_CACHE_REFUSAL is read by runner.sh
tartci_prepare_lane_cache_mounts() {
  local root="$1" host="${2:-}" fetchcontent="$3" shared="${4:-1}"
  TARTCI_LANE_CACHE_REFUSAL=""
  TARTCI_LANE_CACHE_REFUSAL="$(tartci_lane_cache_root_refusal "$root" "$host")" || return 1
  tartci_prepare_disk_root "$root/ccache" || return 1
  tartci_ccache_guard "$root/ccache"
  tartci_prepare_disk_root "$fetchcontent" || return 1
  # Pulp's configure-check replay (tools/cmake/PulpConfigureCheckCache.cmake)
  # keys SDL3's ~180 try_compile results on the SDK, compiler and flags and
  # writes them atomically (tmp + rename), so one host directory can serve
  # every VM on the host. Without a mount the cache lives in the disposable
  # guest and every gate configure re-runs all 192 try_compiles.
  tartci_prepare_disk_root "$root/configure-checks" || return 1
  TARTCI_LANE_CACHE_REFUSAL="$(tartci_lane_cache_root_refusal "$root" "$host")" || return 1
  [ "$shared" = 1 ] || return 0
  TARTCI_LANE_CACHE_REFUSAL="$(tartci_shared_cache_tamper_refusal "$root")" || return 1
  return 0
}

# Every guest writes the shared ccache and configure-checks directories, and
# two things a guest can leave there are code rather than data for whoever
# reads them next: a ccache.conf (prefix_command and friends run on the next
# compile, guest or host), and a configure-checks file, which Pulp's
# PulpConfigureCheckCache.cmake include()s into the next configure. Guests
# read a guest-local ccache config and tartci's host tools read none
# (CCACHE_CONFIGPATH), but a host build that sets CCACHE_DIR to this cache
# still reads it, and Pulp's tools/ci/pulp-worktree.sh writes max_size there.
# So a ccache.conf may hold only plain size and hashing settings (nothing that
# names a command or a path), and a configure-checks file only the lines that
# writer produces.
TARTCI_CCACHE_CONF_RE='^[[:space:]]*(#.*|(max_size[[:space:]]*=[[:space:]]*[0-9]+(\.[0-9]+)?[[:space:]]*[kKMGT]?i?B?|max_files[[:space:]]*=[[:space:]]*[0-9]+|(compression|inode_cache|hash_dir|depend_mode|direct_mode)[[:space:]]*=[[:space:]]*(true|false)|compression_level[[:space:]]*=[[:space:]]*-?[0-9]+|compiler_check[[:space:]]*=[[:space:]]*(content|mtime|none))[[:space:]]*)?$'
TARTCI_CONFIGURE_CHECK_SEED_RE='^(# Generated by PulpConfigureCheckCache\.cmake\. Safe to delete\.|pulp_configure_check_cache_seed\([A-Za-z0-9_.+-]+ "(1|0|TRUE|FALSE|ON|OFF)?" "(Have (symbol|include|includes|function|library|prototype|variable) ([^"\\$;[:cntrl:]]|\\[\\"$;n])+|Test [A-Za-z0-9_]+|Result of TRY_COMPILE)"\))?$'

# Prints `<path> <reason>` for the first file that should not be there.
tartci_shared_cache_tamper_finding(){
  local root="$1" file
  file="$root/ccache/ccache.conf"
  if [ -L "$file" ] || { [ -e "$file" ] && [ ! -f "$file" ]; }; then
    printf '%q is not a regular file\n' "$file"
    return 0
  fi
  if [ -f "$file" ] && ! tartci_shared_cache_file_ok "$file" "$TARTCI_CCACHE_CONF_RE"; then
    printf '%q is a ccache config with a setting beyond size and hashing\n' "$file"
    return 0
  fi
  for file in "$root/configure-checks"/*.[cC][mM][aA][kK][eE]; do
    if [ -L "$file" ] || { [ -e "$file" ] && [ ! -f "$file" ]; }; then
      printf '%q is not a regular file\n' "$file"
      return 0
    fi
    [ -f "$file" ] || continue
    if ! tartci_configure_check_file_ok "$file"; then
      printf '%q holds a line that is not a configure-check seed\n' "$file"
      return 0
    fi
  done
  return 1
}

# grep -v finds a line outside the format (0), finds none (1) or fails (2+):
# only "finds none" is a clean file.
tartci_shared_cache_file_ok(){
  local rc=0
  LC_ALL=C grep -Evq "$2" "$1" || rc=$?
  [ "$rc" -eq 1 ]
}

# The writer never records a CMAKE_ variable, so a seed for one is refused too.
tartci_configure_check_file_ok(){
  local rc=0
  tartci_shared_cache_file_ok "$1" "$TARTCI_CONFIGURE_CHECK_SEED_RE" || return 1
  LC_ALL=C grep -Eq '^pulp_configure_check_cache_seed\(CMAKE_' "$1" || rc=$?
  [ "$rc" -eq 1 ]
}

# Prints the refusal and returns 1 when the shared cache holds a file above.
# TARTCI_CACHE_TAMPER=quarantine instead moves each one into
# <dir>-quarantine/<UTC stamp>-tamper/ (beside the ccache guard's batches)
# and lets the boot go ahead.
tartci_shared_cache_tamper_refusal(){
  local root="$1" mode="${TARTCI_CACHE_TAMPER:-refuse}" finding file qdir stamp
  finding="$(tartci_shared_cache_tamper_finding "$root")" || return 0
  case "$mode" in
    refuse) ;;
    quarantine)
      stamp="$(date -u +%Y%m%dT%H%M%SZ)"
      for file in "$root/ccache/ccache.conf" "$root/configure-checks"/*.[cC][mM][aA][kK][eE]; do
        [ -e "$file" ] || [ -L "$file" ] || continue
        if [ ! -L "$file" ] && [ -f "$file" ]; then
          case "$file" in
            */ccache.conf) tartci_shared_cache_file_ok "$file" "$TARTCI_CCACHE_CONF_RE" && continue ;;
            *) tartci_configure_check_file_ok "$file" && continue ;;
          esac
        fi
        qdir="${file%/*}-quarantine/$stamp-tamper"
        if ! mkdir -p "$qdir" || ! mv -f "$file" "$qdir/"; then
          printf 'shared cache: %s; quarantine into %s failed; remove it\n' "$finding" "$qdir"
          return 1
        fi
        printf 'shared cache: quarantined %q into %s\n' "$file" "$qdir" >&2
      done
      finding="$(tartci_shared_cache_tamper_finding "$root")" || return 0
      printf 'shared cache: %s after quarantine; remove it\n' "$finding"
      return 1 ;;
    *)
      printf 'shared cache: %s (and TARTCI_CACHE_TAMPER=%q is not refuse or quarantine)\n' "$finding" "$mode"
      return 1 ;;
  esac
  printf 'shared cache: %s; inspect and remove it, or set TARTCI_CACHE_TAMPER=quarantine\n' "$finding"
  return 1
}

# Release-tier boots (the job's class label is known before the clone) mount
# neither read-write shared cache, so nothing a PR guest wrote there reaches a
# release build. TARTCI_RELEASE_TIER_NO_SHARED_CACHE=0 restores the mounts;
# TARTCI_RELEASE_TIER_LABELS (comma list) names the release class labels.
# Returns 1 when a boot for these labels must not mount the shared cache.
tartci_labels_mount_shared_cache(){
  local labels="$1" label release
  [ "${TARTCI_RELEASE_TIER_NO_SHARED_CACHE:-1}" = 1 ] || return 0
  IFS=',' read -r -a release <<< "${TARTCI_RELEASE_TIER_LABELS:-pulp-release-tagged}"
  for label in ${release[@]+"${release[@]}"}; do
    [ -n "$label" ] || continue
    case ",$labels," in *",$label,"*) return 1 ;; esac
  done
  return 0
}
